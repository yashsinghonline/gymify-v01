#!/usr/bin/env python3
"""Writes frontend/src/mono-emoji.css and copies the font files beside it.

    npm pack @fontsource-variable/noto-emoji   (or npm i it anywhere)
    python3 scripts/greyscale/emoji-font.py path/to/node_modules/@fontsource-variable/noto-emoji

Noto Emoji is the monochrome emoji font the greyscale fork puts first in its font stack, so an
emoji in a routine's name or a translated line is drawn as an outline in the text colour instead
of in the system's colour font. Fontsource ships it split into subsets with a unicode-range each;
this keeps the split and drops every code point below U+2300 from the ranges (the font also has
digits, '#', '*', (c), (r) and some arrows, which in front of the stack would replace the app's
own), keeping only the zero-width joiner and the keycap mark that emoji sequences are built with.
"""
import re, shutil, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / 'frontend' / 'src'
KEEP_LOW = {0x200d, 0x20e3}
HEAD = """/* A monochrome emoji font, first in the app's font stack (index.css body).
   ----------------------------------------------------------------------------
   Greyscale fork. Emoji are the one colour CSS cannot reach: the system draws them from a colour
   font, in a routine's name, a note, a translated line ("is ready \U0001F389"). Noto Emoji is the same
   set drawn as plain outlines that take the text colour, so with it in front an emoji is one
   more glyph in the label colour.

   The files are Noto Emoji (variable, wght 300-700), Copyright 2013 Google LLC, SIL Open Font
   License 1.1 (fonts/noto-emoji/OFL.txt), as split into subsets by Fontsource. Each @font-face
   names the code points its file holds, so a browser fetches a file only when a page shows one
   of them, and a profile with no emoji anywhere fetches none.

   The ranges are Fontsource's minus everything below U+2300 (kept: the joiner and the keycap
   mark): the font also draws the digits, #, *, (c), (r) and a few arrows, and in front of the
   stack it would have taken every number in the app.

   Generated by scripts/greyscale/emoji-font.py; edit that, not this. */
"""


def main(pkg):
    pkg = Path(pkg)
    css = (pkg / 'index.css').read_text()
    blocks = re.findall(r"src: url\(\./files/(noto-emoji-(\d+)-wght-normal\.woff2)\)[^;]*;\s*unicode-range: ([^;]+);", css)
    if not blocks:
        sys.exit('no @font-face blocks found in ' + str(pkg / 'index.css'))
    fonts = SRC / 'fonts' / 'noto-emoji'
    fonts.mkdir(parents=True, exist_ok=True)
    out = [HEAD]
    for name, _, ranges in sorted(blocks, key=lambda b: int(b[1])):
        keep = []
        for part in (p.strip() for p in ranges.split(',')):
            m = re.match(r'U\+([0-9a-f]+)(?:-([0-9a-f]+))?$', part, re.I)
            lo = int(m.group(1), 16)
            hi = int(m.group(2), 16) if m.group(2) else lo
            if hi < 0x2300:
                if lo == hi and lo in KEEP_LOW:
                    keep.append(part)
                continue
            if lo < 0x2300:
                sys.exit('a range straddles U+2300: ' + part)
            keep.append(part)
        shutil.copyfile(pkg / 'files' / name, fonts / name)
        out.append("@font-face{font-family:'Mono Emoji';font-style:normal;font-display:swap;font-weight:300 700;\n"
                   "  src:url(./fonts/noto-emoji/%s) format('woff2');\n  unicode-range:%s}\n" % (name, ','.join(keep)))
    shutil.copyfile(pkg / 'LICENSE', fonts / 'OFL.txt')
    (SRC / 'mono-emoji.css').write_text('\n'.join(out))
    print('%d subsets -> %s' % (len(blocks), (SRC / 'mono-emoji.css').relative_to(ROOT)))


if __name__ == '__main__':
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
